<#
    Invoke-Build script for OnetimeSecret.

    Tasks:
      Clean     remove output/
      Analyze   PSScriptAnalyzer over src/, tests/ and the build scripts
      Test      Pester unit tests (set OTS_INTEGRATION=1 for the live tests too)
      Build     stage a publishable module in output/OnetimeSecret/<version>/
      Docs      regenerate docs/cmdlets/*.md from comment-based help (platyPS)
      Package   zip the staged module (output/OnetimeSecret-<version>.zip)
      Publish   push the staged module to the PowerShell Gallery
      .         default: Analyze + Test

    Run through ./build.ps1, which installs the required modules first.
#>

[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSReviewUnusedParameter', '', Justification = 'Parameters are consumed by Invoke-Build tasks below.')]
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingCmdletAliases', '', Justification = 'task is the Invoke-Build DSL keyword (an alias of Add-BuildTask by design).')]
param(
    # NuGet API key for Publish; defaults to the PSGALLERY_API_KEY environment variable.
    [string] $ApiKey = $env:PSGALLERY_API_KEY,

    # Repository to publish to. Defaults to PSGallery.
    [string] $Repository = 'PSGallery',

    # Override the module version at build time (e.g. 0.2.0-preview1) to try
    # a build without editing the manifest. The release workflow does not use
    # it; it publishes whatever the manifest says.
    [string] $Version
)

# Load the pinned Pester line before anything can auto-load another one.
# PSScriptAnalyzer resolves commands in the test files while analysing and
# would otherwise pull in the newest installed Pester, after which a 5.x
# import fails with "Assembly with same name is already loaded".
Import-Module Pester -MinimumVersion 5.5.0 -MaximumVersion 5.99.99

$script:ModuleName   = 'OnetimeSecret'
$script:SourcePath   = Join-Path (Join-Path $BuildRoot 'src') $ModuleName
$script:ManifestPath = Join-Path $SourcePath "$ModuleName.psd1"
$script:OutputRoot   = Join-Path $BuildRoot 'output'
$script:TestsPath    = Join-Path $BuildRoot 'tests'
$script:DocsPath     = Join-Path (Join-Path $BuildRoot 'docs') 'cmdlets'
$script:Settings     = Join-Path $BuildRoot 'PSScriptAnalyzerSettings.psd1'

function Get-ManifestVersion {
    $data = Import-PowerShellDataFile -Path $script:ManifestPath
    $base = $data.ModuleVersion
    $prerelease = $data.PrivateData.PSData.Prerelease
    if ($prerelease) { return '{0}-{1}' -f $base, $prerelease }
    return $base
}

task Clean {
    if (Test-Path $OutputRoot) { Remove-Item $OutputRoot -Recurse -Force }
}

task Analyze {
    Import-Module PSScriptAnalyzer -MinimumVersion 1.22.0
    $targets = @(
        (Join-Path $BuildRoot 'src')
        (Join-Path $BuildRoot 'tests')
        (Join-Path $BuildRoot 'build.ps1')
        (Join-Path $BuildRoot 'OnetimeSecret.build.ps1')
    )
    $results = foreach ($target in $targets) {
        Invoke-ScriptAnalyzer -Path $target -Recurse -Settings $Settings
    }
    if ($results) {
        $results | Format-Table -AutoSize RuleName, Severity, ScriptName, Line, Message | Out-String -Width 200 | Write-Host
        throw ('PSScriptAnalyzer reported {0} finding(s).' -f @($results).Count)
    }
    Write-Host 'PSScriptAnalyzer: clean'
}

task Test {
    $configuration = New-PesterConfiguration
    $configuration.Run.Path = $TestsPath
    $configuration.Run.Exit = $false
    $configuration.Run.PassThru = $true
    $configuration.Output.Verbosity = 'Detailed'
    $configuration.TestResult.Enabled = $true
    $configuration.TestResult.OutputFormat = 'NUnitXml'
    $configuration.TestResult.OutputPath = Join-Path $OutputRoot 'testResults.xml'
    $configuration.CodeCoverage.Enabled = $true
    $configuration.CodeCoverage.Path = @(Get-ChildItem -Path $SourcePath -Recurse -Filter '*.ps1' | ForEach-Object FullName)
    $configuration.CodeCoverage.OutputPath = Join-Path $OutputRoot 'coverage.xml'
    $configuration.CodeCoverage.OutputFormat = 'JaCoCo'

    New-Item -ItemType Directory -Path $OutputRoot -Force | Out-Null
    $result = Invoke-Pester -Configuration $configuration

    if ($result.FailedCount -gt 0) {
        throw ('{0} test(s) failed.' -f $result.FailedCount)
    }
}

task Build Clean, {
    $version = if ($Version) { $Version } else { Get-ManifestVersion }
    $baseVersion = $version.Split('-')[0]
    $prerelease = if ($version.Contains('-')) { $version.Split('-', 2)[1] } else { '' }

    $stage = Join-Path (Join-Path $OutputRoot $ModuleName) $baseVersion
    New-Item -ItemType Directory -Path $stage -Force | Out-Null

    # Concatenate every function into a single psm1. Private files first so
    # script-scope state is initialised before anything that uses it.
    $header = @(
        '#Requires -Version 5.1'
        '# OnetimeSecret {0} -- generated by OnetimeSecret.build.ps1; edit src/ instead.' -f $version
        ''
        'Set-StrictMode -Version Latest'
        ''
        '$script:ModuleRoot        = $PSScriptRoot'
        '$script:ModuleVersion     = [string] (Import-PowerShellDataFile -Path (Join-Path $PSScriptRoot ''OnetimeSecret.psd1'')).ModuleVersion'
        '$script:DefaultConnection = $null'
        ''
        '# Windows PowerShell 5.1 inherits the .NET Framework default protocol list,'
        '# which on older Windows builds still excludes TLS 1.2.'
        'if ($PSVersionTable.PSEdition -ne ''Core'') {'
        '    try {'
        '        [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.ServicePointManager]::SecurityProtocol -bor [System.Net.SecurityProtocolType]::Tls12'
        '    }'
        '    catch {'
        '        Write-Verbose (''Could not enable TLS 1.2: {0}'' -f $_.Exception.Message)'
        '    }'
        '}'
        ''
    )

    $sources = @(
        Get-ChildItem -Path (Join-Path $SourcePath 'Private') -Filter '*.ps1' | Sort-Object Name
        Get-ChildItem -Path (Join-Path $SourcePath 'Public')  -Filter '*.ps1' | Sort-Object Name
    )
    $publicNames = @(Get-ChildItem -Path (Join-Path $SourcePath 'Public') -Filter '*.ps1' | ForEach-Object BaseName)

    $body = foreach ($file in $sources) {
        '#region {0}' -f $file.Name
        Get-Content -Path $file.FullName -Raw
        '#endregion {0}' -f $file.Name
        ''
    }

    $footer = @(
        'Export-ModuleMember -Function @('
        ($publicNames | ForEach-Object { "    '{0}'" -f $_ })
        ')'
    )

    $psm1 = Join-Path $stage "$ModuleName.psm1"
    ($header + $body + $footer) -join [System.Environment]::NewLine | Set-Content -Path $psm1 -Encoding UTF8

    Copy-Item -Path (Join-Path $SourcePath "$ModuleName.Format.ps1xml") -Destination $stage
    Copy-Item -Path (Join-Path $SourcePath 'en-US') -Destination $stage -Recurse
    Copy-Item -Path (Join-Path $BuildRoot 'LICENSE') -Destination $stage
    Copy-Item -Path (Join-Path $BuildRoot 'README.md') -Destination $stage
    Copy-Item -Path (Join-Path $BuildRoot 'CHANGELOG.md') -Destination $stage

    # Write the manifest with the resolved version and the real function list.
    # Update-ModuleManifest validates the file first, and that validation
    # insists ModuleVersion matches the version folder, so when -Version
    # overrides the manifest the version has to be substituted up front.
    $stagedManifest = Join-Path $stage "$ModuleName.psd1"
    $manifestText = Get-Content -Path $ManifestPath -Raw
    $manifestText = $manifestText -replace "(?m)^(\s*ModuleVersion\s*=\s*)'[^']*'", ('$1''{0}''' -f $baseVersion)
    Set-Content -Path $stagedManifest -Value $manifestText -Encoding UTF8 -NoNewline

    $manifestParameters = @{
        Path              = $stagedManifest
        ModuleVersion     = $baseVersion
        FunctionsToExport = $publicNames
    }
    if ($prerelease) { $manifestParameters['Prerelease'] = $prerelease }
    Update-ModuleManifest @manifestParameters

    $manifest = Test-ModuleManifest -Path $manifestParameters.Path
    Write-Host ('Built {0} {1} -> {2}' -f $ModuleName, $version, $stage)
    Write-Host ('Exports: {0}' -f ($manifest.ExportedFunctions.Keys -join ', '))
}

task Docs {
    Import-Module platyPS -MinimumVersion 0.14.2
    Get-Module $ModuleName | Remove-Module -Force
    Import-Module $ManifestPath -Force

    if (Test-Path $DocsPath) { Get-ChildItem -Path $DocsPath -Filter '*.md' | Remove-Item -Force }
    New-Item -ItemType Directory -Path $DocsPath -Force | Out-Null

    $docParameters = @{
        Module                = $ModuleName
        OutputFolder          = $DocsPath
        AlphabeticParamsOrder = $true
        Force                 = $true
        ExcludeDontShow       = $true
    }
    New-MarkdownHelp @docParameters | ForEach-Object { Write-Host ('  {0}' -f $_.Name) }

    # platyPS's module page is a template full of placeholders; write a real
    # index from the synopses instead.
    $commands = Get-Command -Module $ModuleName | Sort-Object Noun, Verb
    $index = @(
        '# Cmdlet reference'
        ''
        'Generated from the module''s comment-based help by `./build.ps1 -Task Docs`'
        '(platyPS). Do not edit these files by hand; change the help in'
        '`src/OnetimeSecret/Public/*.ps1` and regenerate.'
        ''
        '| Cmdlet | Synopsis |'
        '| ------ | -------- |'
    )
    foreach ($command in $commands) {
        $synopsis = (Get-Help $command.Name).Synopsis.Trim()
        $index += '| [{0}]({0}.md) | {1} |' -f $command.Name, $synopsis
    }
    $index += ''
    $index += 'See also `Get-Help about_OnetimeSecret`.'
    ($index -join [System.Environment]::NewLine) | Set-Content -Path (Join-Path $DocsPath 'README.md') -Encoding UTF8
    Write-Host ('Wrote {0}' -f (Join-Path $DocsPath 'README.md'))
}

task Package Build, {
    $version = if ($Version) { $Version } else { Get-ManifestVersion }
    $zip = Join-Path $OutputRoot ('{0}-{1}.zip' -f $ModuleName, $version)
    if (Test-Path $zip) { Remove-Item $zip -Force }
    Compress-Archive -Path (Join-Path $OutputRoot $ModuleName) -DestinationPath $zip
    Write-Host ('Packaged {0}' -f $zip)
}

task Publish Build, {
    if (-not $ApiKey) { throw 'An API key is required: pass -ApiKey or set PSGALLERY_API_KEY.' }

    $version = if ($Version) { $Version } else { Get-ManifestVersion }
    $baseVersion = $version.Split('-')[0]
    $stage = Join-Path (Join-Path $OutputRoot $ModuleName) $baseVersion

    # Refuse to clobber: the Gallery rejects re-publishing a version anyway,
    # but failing here gives a clearer message.
    $existing = Find-Module -Name $ModuleName -Repository $Repository -AllVersions -AllowPrerelease -ErrorAction SilentlyContinue |
        Where-Object { $_.Version -eq $version }
    if ($existing) { throw ('{0} {1} is already published to {2}.' -f $ModuleName, $version, $Repository) }

    Publish-Module -Path $stage -Repository $Repository -NuGetApiKey $ApiKey -Verbose
    Write-Host ('Published {0} {1} to {2}' -f $ModuleName, $version, $Repository)
}

task . Analyze, Test
